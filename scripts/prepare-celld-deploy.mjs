import fs from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
const clientDir = path.join(rootDir, "dist", "client");
const serverWranglerPath = path.join(rootDir, "dist", "server", "wrangler.json");
const rootWranglerPath = path.join(rootDir, "wrangler.jsonc");

// 1. Remove files in dist/client that celld deploy rejects (.assetsignore, _worker.js, _routes.json)
for (const forbidden of [".assetsignore", "_worker.js", "_routes.json"]) {
  const target = path.join(clientDir, forbidden);
  if (fs.existsSync(target)) {
    fs.rmSync(target, { recursive: true, force: true });
    console.log(`[prepare-celld-deploy] Removed ${forbidden} from dist/client`);
  }
}

// 1.5 Stamp build version into dist/client/sw.js so browsers detect Service Worker updates on each deploy
const builtSwPath = path.join(clientDir, "sw.js");
if (fs.existsSync(builtSwPath)) {
  const buildVersion = `rodydavis-pwa-${Date.now()}`;
  const swContent = fs.readFileSync(builtSwPath, "utf-8");
  const stampedSw = swContent.replace(
    /const CACHE_NAME = ["'][^"']+["'];/,
    `const CACHE_NAME = "${buildVersion}";`
  );
  fs.writeFileSync(builtSwPath, stampedSw, "utf-8");
  console.log(`[prepare-celld-deploy] Stamped Service Worker cache version: ${buildVersion}`);
}

// 2. Discover the compiled server entry point generated by @astrojs/cloudflare
let compiledMain = "dist/server/entry.mjs";
if (fs.existsSync(serverWranglerPath)) {
  try {
    const serverWrangler = JSON.parse(fs.readFileSync(serverWranglerPath, "utf-8"));
    if (serverWrangler.main) {
      compiledMain = path.posix.join("dist/server", serverWrangler.main);
    }
  } catch (err) {
    console.warn("[prepare-celld-deploy] Could not parse dist/server/wrangler.json:", err);
  }
}

// 3. Write a celld-compatible wrangler config
const celldWranglerConfig = {
  name: "rodydavis",
  main: compiledMain,
  compatibility_date: "2026-01-01",
  compatibility_flags: ["nodejs_compat", "sqlite_vec"],
  assets: {
    directory: "./dist/client",
    binding: "ASSETS",
  },
  durable_objects: {
    bindings: [
      {
        name: "CONTENT_INDEX",
        class_name: "ContentIndex",
      },
    ],
  },
  migrations: [
    {
      tag: "v1",
      new_sqlite_classes: ["ContentIndex"],
    },
  ],
};

fs.writeFileSync(
  path.join(rootDir, "wrangler.celld.jsonc"),
  JSON.stringify(celldWranglerConfig, null, 2) + "\n",
  "utf-8"
);

if (process.env.CI === "true" || process.argv.includes("--write-wrangler")) {
  fs.writeFileSync(
    rootWranglerPath,
    JSON.stringify(celldWranglerConfig, null, 2) + "\n",
    "utf-8"
  );
  console.log(`[prepare-celld-deploy] Updated root wrangler.jsonc for CI celld deploy`);
}

console.log(`[prepare-celld-deploy] Ready for celld deploy (main: ${compiledMain})`);
